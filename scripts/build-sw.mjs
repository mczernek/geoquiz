#!/usr/bin/env node
// Writes dist/sw.js after `expo export -p web`: a service worker that precaches the whole exported app (JS, fonts,
// flags), so the web app opens and works offline after one visit (docs/specs/sync.md → Web).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(dist)
  .map((p) => relative(dist, p))
  .filter((p) => !p.endsWith('.map') && p !== 'sw.js' && !p.startsWith('.'))
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);
const urls = files.map((f) => `/${f.split('\\').join('/')}`).map((u) => (u === '/index.html' ? '/' : u));

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = 'geoquiz-${version}';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('geoquiz-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // App routes: the network when online (fresh deploys), the cached shell when offline.
    event.respondWith(fetch(request).catch(() => caches.match('/', { cacheName: CACHE })));
    return;
  }
  event.respondWith(caches.match(request, { cacheName: CACHE }).then((hit) => hit || fetch(request)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files, cache ${version}`);
