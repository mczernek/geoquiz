#!/usr/bin/env node
// Downloads a 640 px wide PNG flag per quiz country from flagcdn.com (public-domain flag images) into assets/flags
// and generates src/data/flags.ts, the static require map Metro needs. Run after build-data: pnpm flags
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';

const root = new URL('..', import.meta.url).pathname;
const countries = JSON.parse(await readFile(`${root}src/data/countries.json`, 'utf8'));
mkdirSync(`${root}assets/flags`, { recursive: true });

for (const { code } of countries) {
  const file = `${root}assets/flags/${code.toLowerCase()}.png`;
  if (existsSync(file)) continue;
  const res = await fetch(`https://flagcdn.com/w640/${code.toLowerCase()}.png`);
  if (!res.ok) throw new Error(`${code}: HTTP ${res.status}`);
  writeFileSync(file, Buffer.from(await res.arrayBuffer()));
}

const lines = countries.map(({ code }) => `  ${code}: require('../../assets/flags/${code.toLowerCase()}.png'),`);
writeFileSync(
  `${root}src/data/flags.ts`,
  `// Generated by scripts/fetch-flags.mjs. Do not edit.\n\n` + `export const FLAGS: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`flags: ${countries.length}`);
